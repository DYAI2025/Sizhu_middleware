/**
 * Registry of the BaZi Year-Pillar poster template variants.
 *
 * Data-only: each entry is a frozen template definition the image-generation lane
 * reads (a prose seed, a structured visual direction, the fixed §10 negative
 * constraints, and the placeholder keys the renderer substitutes). The registry
 * itself has no behaviour beyond lookup.
 *
 * Lookup is fail-closed: an unknown id returns an explicit BLOCKED sentinel rather
 * than `undefined`, so a caller cannot silently treat "template not found" as
 * "proceed without a template".
 */

export type RegionPolicy = "CN_SIMPLIFIED";

export type TemplateVariantId =
  | "BEIJING_MODERN_MAINLAND"
  | "SICHUAN_CLASSICAL_MAINLAND";

export interface VisualDirection {
  composition: string;
  materialLanguage: string[];
  motifs: string[];
  mood: string;
}

export interface TemplateDefinition {
  id: string;
  variantId: TemplateVariantId;
  regionPolicy: RegionPolicy;
  /** Seed prose for the LLM prose lane. */
  imageGenerationPromptSeed: string;
  visualDirection: VisualDirection;
  /** The fixed §10 negative-constraint string (shared by all variants). */
  negativeConstraints: string;
  /** Names of the {{...}} placeholders the renderer substitutes. */
  placeholderKeys: string[];
}

/** Returned by getTemplate when the requested id is not registered. */
export interface BlockedTemplateResult {
  status: "BLOCKED";
  reason: "UNKNOWN_TEMPLATE";
}

