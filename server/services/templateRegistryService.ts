const TEMPLATES: Record<string, TemplateDefinition> = {
  [BEIJING_MODERN.id]: BEIJING_MODERN,
  [SICHUAN_CLASSICAL.id]: SICHUAN_CLASSICAL,
};

/**
 * Look up a template by id.
 * @returns the template definition, or a BLOCKED/UNKNOWN_TEMPLATE sentinel.
 */
export function getTemplate(
  id: string
): TemplateDefinition | BlockedTemplateResult {
  const template = TEMPLATES[id];
  if (!template) {
    return { status: "BLOCKED", reason: "UNKNOWN_TEMPLATE" };
  }
  return template;
}

/** List the ids of all registered templates. */
export function listTemplates(): string[] {
  return Object.keys(TEMPLATES);
}
